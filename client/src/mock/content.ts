import type { Block, ExamFormat, Mode, QuestionType } from '../api/types';

export interface ContentKp { t: string; s: string; modes?: Mode[] }
export interface ContentTopic { title: string; pages: number; homework?: boolean; kps: ContentKp[] }
export interface ContentChapter { title: string; material: string; topics: ContentTopic[] }
export interface ContentMaterial { key: string; title: string; kind: 'slides' | 'homework' | 'notes' | 'review' | 'past_paper'; pages: number }
export interface ContentQuestion {
  type: QuestionType; score: number; kp: string; stem: Block[];
  options?: [string, string][]; key?: string; answer: string; steps: Block[][];
  rubric?: [string, number][]; hints: [string, string];
}
export interface ContentCourse {
  key: 'os' | 'math' | 'ds';
  name: string;
  materials: ContentMaterial[];
  chapters: ContentChapter[];
  questions: ContentQuestion[];
  explain: Record<string, Block[][]>;
  focus: string;
  format: Omit<ExamFormat, 'basis'>;
}

export const T = (text: string): Block => ({ kind: 'text', text });
export const L = (items: string[], ordered = true): Block => ({ kind: 'list', ordered, items });
const TB = (header: string[], rows: string[][]): Block => ({ kind: 'table', header, rows });
const C = (text: string, lang: string | null = null): Block => ({ kind: 'code', text, lang });
const F = (text: string): Block => ({ kind: 'formula', text });

const k = (t: string, s: string, modes?: Mode[]): ContentKp => ({ t, s, modes });

const format = (single: number, fill: number, calc: number, short: number, proof = 0, design = 0, duration = 120): Omit<ExamFormat, 'basis'> => ({
  types: [
    { type: 'single', count: single, score: 2 },
    { type: 'fill', count: fill, score: 4 },
    { type: 'calc', count: calc, score: 10 },
    { type: 'short', count: short, score: 8 },
    { type: 'proof', count: proof, score: 10 },
    { type: 'design', count: design, score: 12 },
  ],
  duration_min: duration,
  open_book: false,
});

